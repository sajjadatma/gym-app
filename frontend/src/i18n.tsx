const dictionaries: Record<Locale, Record<TranslationKey, string>> = { fa, en }

type I18nContextValue = {
  locale: Locale
  direction: "rtl" | "ltr"
  setLocale: (locale: Locale) => void
  t: (key: TranslationKey, values?: Record<string, string | number>) => string
  formatNumber: (value: number | string | null | undefined) => string
  formatDate: (
    value: string | null | undefined,
    withWeekday?: boolean,
  ) => string
  formatDateTime: (value: string | null | undefined) => string
  localizeDigits: (value: string | number) => string
  normalizeDigits: (value: string) => string
}

const I18nContext = createContext<I18nContextValue | null>(null)

const FA_DIGITS = "۰۱۲۳۴۵۶۷۸۹"

function applyDocumentLocale(locale: Locale) {
  document.documentElement.lang = locale === "fa" ? "fa-IR" : "en"
  document.documentElement.dir = locale === "fa" ? "rtl" : "ltr"
}

export function I18nProvider({ children }: { children: ReactNode }) {
  const [locale, setLocaleState] = useState<Locale>(() => {
    const stored = localStorage.getItem("gym.locale")
    return stored === "en" ? "en" : "fa"
  })

  const setLocale = useCallback((nextLocale: Locale) => {
    localStorage.setItem("gym.locale", nextLocale)
    setLocaleState(nextLocale)
  }, [])

  useEffect(() => {
    applyDocumentLocale(locale)
    document.title = dictionaries[locale]["app.name"]
  }, [locale])

  const value = useMemo<I18nContextValue>(() => {
    const dictionary = dictionaries[locale]
    const numberFormatter = new Intl.NumberFormat(
      locale === "fa" ? "fa-IR" : "en-US",
      { maximumFractionDigits: 2 },
    )
    const localizeDigits = (input: string | number) => {
      if (locale === "en") return String(input)
      return String(input).replace(/\d/g, (digit) => FA_DIGITS[Number(digit)])
    }
    return {
      locale,
      direction: locale === "fa" ? "rtl" : "ltr",
      setLocale,
      t: (key, values) => {
        let message = dictionary[key] ?? key
        if (values) {
          for (const [name, replacement] of Object.entries(values)) {
            message = message.split(`{${name}}`).join(String(replacement))
          }
        }
        return message
      },
      formatNumber: (input) => {
        if (input === null || input === undefined || input === "") return "—"
        const numeric = typeof input === "number" ? input : Number(input)
        if (Number.isNaN(numeric)) return String(input)
        return numberFormatter.format(numeric)
      },
      formatDate: (input, withWeekday = false) => {
        if (!input) return "—"
        const dateOnly = /^\d{4}-\d{2}-\d{2}$/.test(input)
        const date = new Date(dateOnly ? `${input}T00:00:00` : input)
        if (Number.isNaN(date.getTime())) return "—"
        return new Intl.DateTimeFormat(locale === "fa" ? "fa-IR" : "en-US", {
          calendar: locale === "fa" ? "persian" : "gregory",
          year: "numeric",
          month: "long",
          day: "numeric",
          ...(withWeekday ? { weekday: "long" } : {}),
        }).format(date)
      },
      formatDateTime: (input) => {
        if (!input) return "—"
        const date = new Date(input)
        if (Number.isNaN(date.getTime())) return "—"
        return new Intl.DateTimeFormat(locale === "fa" ? "fa-IR" : "en-US", {
          calendar: locale === "fa" ? "persian" : "gregory",
          dateStyle: "medium",
          timeStyle: "short",
        }).format(date)
      },
      localizeDigits,
      normalizeDigits: (input) =>
        input
          .replace(/[۰-۹]/g, (digit) => String(FA_DIGITS.indexOf(digit)))
          .replace(/[٠-٩]/g, (digit) => String("٠١٢٣٤٥٦٧٨٩".indexOf(digit))),
    }
  }, [locale, setLocale])

  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>
}

export function useI18n() {
  const context = useContext(I18nContext)
  if (!context) throw new Error("useI18n must be used inside I18nProvider")
  return context
}

